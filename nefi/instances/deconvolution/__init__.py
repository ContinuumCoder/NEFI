"""deconvolution — 2-D image deblurring with Gaussian / motion / disk PSFs.

Recover a non-negative image ``x`` from ``y = k ∗ x + n`` (Gaussian noise) or
``y ~ Poisson(peak · (k ∗ x) + background)`` (photon counts). The forward operator is a
zero-padded (non-periodic) :class:`~nefi.operators.FFTConvolution` whose PSF is a *function of the
grid spacing*, so it is rebuilt consistently at every curriculum resolution. Data are generated by
the same physics on a 2× finer grid in float64 and area-averaged onto the detector grid
(``fidelity_tag="blur-2x-float64"``, inverse-crime guard). The prior is a coordinate neural field
with a non-negative head (``Softplus`` or ``Bounded(0, 1)``) plus isotropic TV (NeFTY Eq. 22),
solved with the NeTMY two-stage multiscale curriculum (Tab. 6).

Baselines: ``grid`` (free pixels, Tikhonov/Grid-Opt style), ``deep_decoder``, ``gaussian_splat``
(designed for ``sparse_dots``), ``admm`` (grid + ℓ1/box ADMM) and the closed-form ``wiener``
filter (:func:`wiener`).
"""

